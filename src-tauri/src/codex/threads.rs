use crate::remote_backend;
use crate::shared::codex_core;
use crate::shared::runs_core::types::RunContext;
use crate::shared::runs_rpc;
use crate::state::AppState;
use serde_json::json;
use serde_json::Value;
use tauri::AppHandle;
use tauri::State;

#[tauri::command]
pub(crate) async fn start_thread(
    run_context: Option<RunContext>,
    workspace_id: String,
    state: State<'_, AppState>,
    app: AppHandle,
) -> Result<Value, String> {
    if remote_backend::is_remote_mode(&*state).await {
        return remote_backend::call_remote(
            &*state,
            app,
            "start_thread",
            json!({ "workspaceId": workspace_id, "runContext": run_context }),
        )
        .await;
    }

    codex_core::threads::start_thread_core(
        runs_rpc::tracking(&state.storage_path, run_context),
        &state.sessions,
        &state.workspaces,
        workspace_id,
    )
    .await
}

